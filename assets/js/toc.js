
document.addEventListener("DOMContentLoaded", function () {

  // Find the main content section and navigation list
  const content = document.querySelector("section");
  const list = document.getElementById("toc-list");
  const toc = document.getElementById("toc");

  if (!content || !list || !toc) return;

  // Find all h1, h2 and h3 headings
  const headings = content.querySelectorAll("h1, h2, h3");

  headings.forEach(function (heading) {

    // Exclude Midnight's page title and footer credits
    if (heading.closest("#title") || heading.closest("#credits")) {
      return;
    }

    // Use the heading ID generated by Jekyll
    if (!heading.id) return;

    // Create a list item reflecting the heading level
    const item = document.createElement("li");
    item.className = "toc-" + heading.tagName.toLowerCase();

    // Create a link to the heading
    const link = document.createElement("a");
    link.href = "#" + encodeURIComponent(heading.id);
    link.textContent = heading.textContent.trim();

    // Add the link to the navigation
    item.appendChild(link);
    list.appendChild(item);

  });

  // Hide the navigation if no headings were found
  if (!list.children.length) {
    toc.hidden = true;
  }

});
